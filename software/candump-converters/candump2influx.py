import influxdb_client
from influxdb_client import Point, WritePrecision, InfluxDBClient
from influxdb_client.client.write_api import SYNCHRONOUS
import argparse
import logging
import json


def init_logger():
    logging.basicConfig(level=logging.DEBUG)
    logger = logging.getLogger(__name__)
    return logger


def parse_can(file_path, bucket, org, no_timestamp, url, token, logger):
    with open(file_path, "r") as file:
        for line in file:
            try:
                with InfluxDBClient(url=url, token=token, org=org) as client:
                    parts = line.strip().split()
                    timestamp = float(parts[0].strip("()")) * 1e9  # Convert seconds to nanoseconds
                    can_channel = parts[1]
                    frame = parts[2].split('#')
                    can_id = frame[0]
                    data = frame[1]

                    bytes_list = [data[i:i + 2] for i in range(0, len(data), 2)]

                    point = (
                        Point("can_data")
                        .tag("can_channel", can_channel)
                        .tag("can_id", can_id)
                    )
                    for index, byte in enumerate(bytes_list):
                        point = point.field(f"byte_{index}", int(byte, 16))

                    if not no_timestamp:
                        point = point.time(int(timestamp), WritePrecision.NS)

                    logger.debug(f"Writing point: {point.to_line_protocol()} to {bucket} at {org}")

                    response = client.write_api(write_options=SYNCHRONOUS).write(bucket=bucket, org=org, record=point)
            except Exception as e:
                logger.error(f"Error processing line: {line}. Error: {e}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Parse and write CAN log to an InfluxDB database.\033[94m Please ensure there are timestamps in the log file.\033[0m")
    parser.add_argument("can_log_dump", help="Path to the CAN log file")
    parser.add_argument("influxdb_config_file", nargs='?', default=None, help="Path to the InfluxDB configuration file. Autogenerated if not provided.\033[91m Warning: this will overwrite and produce an insecure token within the file influxdb-config.json\033[0m")
    parser.add_argument("--no-timestamp", help="Do not use timestamps from the log file", action="store_true")
    args = parser.parse_args()
    if args.influxdb_config_file is None:
        with open("influxdb-config.json", "w") as file:
            file.write('{"token": "your-token", "url": "http://localhost:8086", "org": "your-org", "bucket": "your-bucket"}')
        with open("influxdb-config.json", "r") as file:
            config = json.load(file)
    else:
        with open(args.influxdb_config_file, "r") as file:
            config = json.load(file)
    args.url = config["url"]
    args.token = config["token"]
    args.org = config["org"]
    args.bucket = config["bucket"]
    logger = init_logger()
    parse_can(args.can_log_dump, args.bucket, args.org, args.no_timestamp, args.url, args.token, logger)